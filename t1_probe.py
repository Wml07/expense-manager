# 目的：把 t1.py 的三问连跑多轮，看同一份人设到底稳不稳
# 为什么要跑多轮：单次跑过 ≠ 每次都能跑过。多跑几轮才看得出"稳不稳"

from tools import ask      # 借工具箱里的 ask（人设一整块在 tools.py 里，这里不动它）

# 连跑 5 轮，每轮都是同样三问 —— 唯一变的是模型的"手气"
for i in range(5):
    print(f"\n========== 第 {i+1} 轮 ==========")
    print("① 记账 →", ask("今天早饭23，午饭60，晚饭25"))
    print("② 写诗 →", ask("帮我写一首诗"))
    print("③ 推荐 →", ask("推荐个便宜点的手机"))
