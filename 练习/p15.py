# p15.py —— class 第一课：类 = 造东西的模具
# 这一课只吃一个概念：模具 和 用模具造出来的东西

# ==================== 第一步：画一张模具 ====================
class Zhang:                            # class 后面跟模具的名字（首字母习惯大写）
    def __init__(self, desc, amount):   # 造东西时自动跑的"初始化"工序
        self.desc = desc                # 把传进来的 desc，存到"这一件"身上
        self.amount = amount            # 把传进来的 amount，存到"这一件"身上

# ==================== 第二步：拿模具造两件 ====================
a = Zhang("早饭", 23)                   # 造第 1 件：一件"早饭 23"
b = Zhang("午饭", 60)                   # 造第 2 件：一件"午饭 60"

# ==================== 第三步：看看造出来的东西 ====================
print(a.desc, a.amount)                 # 早饭 23
print(b.desc, b.amount)                 # 午饭 60

# ==================== 第四步：证明它们各是各的 ====================
print("两笔加起来：", a.amount + b.amount)   # 83，说明两件数据互不干扰

# ==================== 第五步：看看模具本身长什么样 ====================
print("模具长这样：", Zhang)             # <class '__main__.Zhang'> —— 它本身是"模具"
print("造出来的长这样：", a)              # <__main__.Zhang object at 0x...> —— 它是"一件实物"
